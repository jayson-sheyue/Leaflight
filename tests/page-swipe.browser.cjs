const {chromium}=require('playwright'),assert=require('node:assert/strict'),http=require('node:http'),fs=require('node:fs'),path=require('node:path');
(async()=>{
 const root=path.resolve('dist'),server=http.createServer((req,res)=>{const file=path.resolve(root,'.'+(req.url==='/'?'/index.html':req.url.split('?')[0]));if(!file.startsWith(root+path.sep)&&file!==root){res.writeHead(404).end();return;}try{const type=file.endsWith('.html')?'text/html':file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'application/octet-stream';res.setHeader('Content-Type',type);res.end(fs.readFileSync(file));}catch{res.writeHead(404).end();}});
 let browser;
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const port=server.address().port;
 try{
  browser=await chromium.launch({headless:true,...(fs.existsSync('/Applications/Google Chrome.app')?{channel:'chrome'}:{})});
  const page=await browser.newPage({viewport:{width:1280,height:900},hasTouch:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto('http://127.0.0.1:'+port);
  await page.locator('.book-title').first().click();
  await page.locator('#reader-scroll').waitFor();
  await page.evaluate(()=>{const animate=Element.prototype.animate;Element.prototype.animate=function(frames,options){const staged=this.classList?.contains('page-turn-stage')||this.closest?.('.page-turn-stage');if(staged){const base=typeof options==='number'?{duration:options}:{...options};options={...base,duration:Math.max(900,base.duration||0)};}return animate.call(this,frames,options);};});
  async function place(){return page.evaluate(()=>{const el=document.querySelector('#reader-scroll');return {left:el.scrollLeft,top:el.scrollTop,width:el.clientWidth,chapter:document.querySelector('.toc-item.selected')?.dataset.chapter||'0',turning:document.body.dataset.turning==='true'};});}
  function turns(before,after){const pageOf=p=>Math.round(p.left/Math.max(1,p.width));const chapters=Number(after.chapter)-Number(before.chapter);if(!chapters)return pageOf(after)-pageOf(before);if(chapters===1&&pageOf(after)===0)return 1;return chapters+pageOf(after);}
  async function settled(){await page.waitForFunction(()=>document.body.dataset.turning!=='true'&&!document.querySelector('.page-turn-stage'));}
  async function clearSelection(){await page.evaluate(()=>getSelection()?.removeAllRanges());}
  async function swipe(dx,dy){const box=await page.locator('#reader-scroll').boundingBox();const x=box.x+box.width*0.72,y=box.y+box.height*0.46;const cdp=await page.context().newCDPSession(page);const point=(px,py)=>({x:px,y:py,id:1});await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point(x,y)]});for(let i=1;i<=8;i++){await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[point(x+dx*i/8,y+dy*i/8)]});await new Promise(resolve=>setTimeout(resolve,16));}const during=await place();await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await cdp.detach();return during;}
  await page.locator('[data-action=appearance]').click();
  assert.match(await page.locator('#reader-form').innerText(),/双指横滑/);
  await page.selectOption('[name=mode]','pages');
  await page.selectOption('[name=effect]','slide');
  await page.locator('button.close[data-action=close]').click();
  await page.locator('.reader-pane[data-mode=pages]').waitFor();
  assert.equal(await page.locator('#reader-scroll').evaluate(el=>getComputedStyle(el).touchAction),'pan-y');
  const origin=await place();
  let during=await swipe(0,220);
  assert.equal(during.left,origin.left,'vertical drag must not scrub the page');
  await settled();
  assert.equal(turns(origin,await place()),0,'vertical drag must not turn the page');
  during=await swipe(-36,0);
  assert.equal(during.left,origin.left,'a short drag must not scrub the page');
  await settled();
  assert.equal(turns(origin,await place()),0,'a short drag must not turn the page');
  const box=await page.locator('#reader-scroll').boundingBox();
  const beforeMouse=await place();
  await page.mouse.move(box.x+box.width*0.72,box.y+box.height*0.46);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*0.72-40,box.y+box.height*0.46,{steps:6});
  during=await place();
  await page.mouse.up();
  await settled();
  assert.equal(during.left,beforeMouse.left,'a short mouse drag must not scrub the page');
  assert.equal(turns(beforeMouse,await place()),0,'a short mouse drag must not turn the page');
  await page.mouse.move(box.x+box.width*0.55,box.y+box.height*0.3);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*0.55,box.y+box.height*0.3+180,{steps:6});
  during=await place();
  await page.mouse.up();
  await settled();
  assert.equal(during.left,beforeMouse.left,'a vertical mouse drag must not scrub the page');
  assert.equal(turns(beforeMouse,await place()),0,'a vertical mouse drag must not turn the page');
  await page.evaluate(()=>{const text=document.querySelector('#prose p')?.firstChild;if(!text)return;const range=document.createRange();range.setStart(text,0);range.setEnd(text,Math.min(8,text.textContent.length));const selection=getSelection();selection.removeAllRanges();selection.addRange(range);});
  await page.mouse.move(box.x+box.width*0.72,box.y+box.height*0.46);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*0.22,box.y+box.height*0.46,{steps:8});
  await page.mouse.up();
  await settled();
  assert.equal(turns(beforeMouse,await place()),0,'an existing text selection must keep a mouse drag from turning');
  await clearSelection();
  const mouseStage=page.locator('.page-turn-stage').waitFor();
  await page.mouse.move(box.x+box.width*0.72,box.y+box.height*0.46);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*0.22,box.y+box.height*0.46,{steps:8});
  during=await place();
  await page.mouse.up();
  assert.equal(during.left,beforeMouse.left,'a mouse drag must not scroll the columns before the page turn');
  await mouseStage;
  assert.equal(await page.locator('.page-turn-stage').getAttribute('data-effect'),'slide');
  await settled();
  assert.equal(turns(beforeMouse,await place()),1,'one horizontal mouse drag turns one page');
  const held=await place();
  await page.evaluate(()=>{const text=document.querySelector('#prose p')?.firstChild;if(!text)return;const range=document.createRange();range.setStart(text,0);range.setEnd(text,Math.min(8,text.textContent.length));const selection=getSelection();selection.removeAllRanges();selection.addRange(range);});
  await swipe(-260,0);
  await settled();
  assert.equal(turns(held,await place()),0,'an existing text selection must keep the page still');
  await clearSelection();
  const beforeTurn=await place();
  const stage=page.locator('.page-turn-stage').waitFor();
  during=await swipe(-280,0);
  assert.equal(during.left,beforeTurn.left,'the finger must not scroll the columns before the page turn');
  await stage;
  assert.equal(await page.locator('.page-turn-stage').getAttribute('data-effect'),'slide');
  await settled();
  const once=await place();
  assert.equal(turns(beforeTurn,once),1,'one horizontal drag turns one page');
  const beforeDouble=await place();
  const first=swipe(-280,0);
  await page.locator('.page-turn-stage').waitFor();
  await swipe(-280,0);
  await first;
  await settled();
  assert.equal(turns(beforeDouble,await place()),1,'a second drag during the effect does not skip a page');
  const beforeButton=await place();
  await page.locator('[data-action=next]').click();
  await page.locator('.page-turn-stage').waitFor();
  await settled();
  assert.equal(turns(beforeButton,await place()),1,'the next button still turns one page');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.evaluate(()=>{window.__sawStage=false;new MutationObserver(()=>{if(document.querySelector('.page-turn-stage'))window.__sawStage=true;}).observe(document.body,{childList:true,subtree:true});});
  const beforeReduced=await place();
  await swipe(-280,0);
  await page.waitForFunction(before=>{const el=document.querySelector('#reader-scroll'),chapter=document.querySelector('.toc-item.selected')?.dataset.chapter||'0';return el.scrollLeft!==before.left||chapter!==before.chapter;},beforeReduced);
  assert.equal(await page.evaluate(()=>window.__sawStage),false,'reduced motion keeps the swipe but skips the effect');
  assert.equal(turns(beforeReduced,await place()),1);
  await page.emulateMedia({reducedMotion:'no-preference'});
  const beforeWheel=await place();
  const wheelBox=await page.locator('#reader-scroll').boundingBox();
  await page.mouse.move(wheelBox.x+wheelBox.width*0.5,wheelBox.y+wheelBox.height*0.5);
  await page.mouse.wheel(30,0);
  await settled();
  assert.equal(turns(beforeWheel,await place()),0,'a short trackpad swipe must not turn the page');
  await page.mouse.wheel(0,180);
  await settled();
  assert.equal(turns(beforeWheel,await place()),0,'a vertical trackpad swipe must not turn the page');
  await page.evaluate(()=>{const text=document.querySelector('#prose p')?.firstChild;if(!text)return;const range=document.createRange();range.setStart(text,0);range.setEnd(text,Math.min(8,text.textContent.length));const selection=getSelection();selection.removeAllRanges();selection.addRange(range);});
  await page.mouse.wheel(200,0);
  await settled();
  assert.equal(turns(beforeWheel,await place()),0,'an existing text selection must keep a trackpad swipe from turning');
  await clearSelection();
  const wheelStage=page.locator('.page-turn-stage').waitFor();
  await page.mouse.wheel(80,0);
  await page.mouse.wheel(160,0);
  await page.mouse.wheel(160,0);
  await wheelStage;
  assert.equal(await page.locator('.page-turn-stage').getAttribute('data-effect'),'slide');
  await settled();
  assert.equal(turns(beforeWheel,await place()),1,'one horizontal trackpad swipe turns one page and ignores the rest of the gesture');
  await page.waitForTimeout(420);
  const beforeNextWheel=await place();
  await page.mouse.wheel(160,0);
  await page.locator('.page-turn-stage').waitFor();
  await settled();
  assert.equal(turns(beforeNextWheel,await place()),1,'a trackpad swipe after the gesture ends turns the next page');
  await page.locator('[data-action=appearance]').click();
  await page.selectOption('[name=mode]','scroll');
  await page.locator('button.close[data-action=close]').click();
  await page.locator('.reader-pane[data-mode=scroll]').waitFor();
  assert.equal(await page.locator('#reader-scroll').evaluate(el=>getComputedStyle(el).touchAction),'auto');
  const beforeScroll=await place();
  await swipe(-280,8);
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const afterScroll=await place();
  assert.equal(afterScroll.chapter,beforeScroll.chapter);
  assert.equal(afterScroll.turning,false);
  assert(Math.abs(afterScroll.top-beforeScroll.top)<40,'scroll mode keeps vertical reading instead of paging');
  await page.mouse.move(wheelBox.x+40,wheelBox.y+40);
  await page.mouse.wheel(200,0);
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  assert.equal((await place()).turning,false,'scroll mode does not turn a page for a trackpad swipe');
  await page.locator('[data-action=appearance]').click();
  await page.selectOption('[name=mode]','pages');
  await page.locator('button.close[data-action=close]').click();
  await page.locator('[data-action=focus-panel][data-panel=reader]').click();
  await page.waitForFunction(()=>!document.querySelector('#focus-chrome')?.classList.contains('shown'),null,{timeout:4500});
  await swipe(-280,0);
  await settled();
  assert.equal(await page.locator('#focus-chrome').evaluate(el=>el.classList.contains('shown')),false,'turning by drag does not reveal the full-window controls');
  const quiet=await page.locator('#reader-scroll').boundingBox();
  await page.touchscreen.tap(quiet.x+quiet.width*0.5,quiet.y+quiet.height*0.4);
  await page.locator('#focus-chrome.shown').waitFor();
  await page.waitForFunction(()=>!document.querySelector('#focus-chrome')?.classList.contains('shown'),null,{timeout:4500});
  await page.mouse.click(quiet.x+quiet.width*0.5,quiet.y+quiet.height*0.4);
  await page.locator('#focus-chrome.shown').waitFor();
  await page.setViewportSize({width:834,height:1112});
  await page.waitForFunction(()=>{const el=document.querySelector('#reader-scroll'),pageWidth=Math.max(1,el.clientWidth);return Math.abs(el.scrollLeft-Math.round(el.scrollLeft/pageWidth)*pageWidth)<2;});
  await settled();
  assert.equal(await page.locator('#reader-scroll').evaluate(el=>getComputedStyle(el).touchAction),'pan-y');
  const beforePortrait=await place();
  during=await swipe(-240,0);
  assert.equal(during.left,beforePortrait.left,'portrait drag must not scrub the columns');
  await page.locator('.page-turn-stage').waitFor();
  await settled();
  assert.equal(turns(beforePortrait,await place()),1,'portrait drag turns one page');
  assert.deepEqual(errors,[]);
  console.log('PASS: paged touch and mouse drags each turn one page with the effect; short, vertical, selected, scroll-mode, and in-flight drags do not. Reduced motion still turns. A drag does not open full-window controls.');
 }finally{if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));}
})().catch(e=>{console.error(e);process.exitCode=1;});
